extern alias ApogeuHost;

using System.Globalization;
using System.Text.Json;
using Apogeu.Operators.Infrastructure.Catalog;
using Apogeu.Security.Tests.Support;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.AspNetCore.TestHost;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Xunit;
using HostProgram = ApogeuHost::Program;

namespace Apogeu.DemoCasino.Tests.Support;

/// <summary>
/// The real Apogeu (the Host in memory, WebApplicationFactory) in Development on real PostgreSQL and Redis, as the
/// Operators tests of SPEC-0020 start it: one demo operator API key and the game base URL generated by the test
/// (ADR-0014), the Operators hosted services kept (migrations and the Development seed: demo operator, the Pipa enabled,
/// BRL limits), the other modules' hosted services removed. The DemoCasino reaches it through <see cref="CreateHandler"/>,
/// the in-memory network of the test server, so its real signing pipeline talks to the real HMAC verifier.
/// </summary>
internal sealed class ApogeuApiHost : IAsyncDisposable
{
    /// <summary>The game client origin configured in the Apogeu (<c>Operators:GameBaseUrl</c>): the base of the kit URLs.</summary>
    public static readonly Uri GameBaseUrl = new("https://game.apogeu.test");

    private const string GamesPath = "/api/v1/games";

    /// <summary>The exchange of a launch token for a player session (SPEC-0009@1 §6), public: what the game does on load.</summary>
    private const string SessionsPath = "/api/v1/sessions";

    private const string OpenApiPath = "/openapi/v1.json";

    private readonly WebApplicationFactory<HostProgram> _factory;

    private ApogeuApiHost(WebApplicationFactory<HostProgram> factory, TestApiKey key)
    {
        _factory = factory;
        Key = key;
    }

    /// <summary>The active API key of the demo operator.</summary>
    public TestApiKey Key { get; }

    public static async Task<ApogeuApiHost> StartAsync(string postgresServerConnectionString, string redisConnectionString, CancellationToken cancellationToken)
    {
        var database = await TestDatabase.CreateAsync(postgresServerConnectionString, cancellationToken).ConfigureAwait(false);
        var key = TestApiKey.Generate();
        var signingKey = Convert.ToBase64String(System.Security.Cryptography.RandomNumberGenerator.GetBytes(32));

        var factory = new WebApplicationFactory<HostProgram>().WithWebHostBuilder(host =>
        {
            host.UseEnvironment("Development");
            host.UseSetting("ConnectionStrings:apogeu", database);
            host.UseSetting("ConnectionStrings:redis", redisConnectionString);
            host.UseSetting("Operators:GameBaseUrl", GameBaseUrl.ToString().TrimEnd('/'));
            host.UseSetting("Operators:Demo:ApiKeys:0:Id", key.Id);
            host.UseSetting("Operators:Demo:ApiKeys:0:Secret", key.Secret);
            host.UseSetting("Security:PlayerSession:SigningKey", signingKey);
            host.ConfigureTestServices(services =>
            {
                var otherModules = services
                    .Where(d => d.ServiceType == typeof(IHostedService)
                        && d.ImplementationType?.Assembly.GetName().Name is { } assembly
                        && assembly.StartsWith("Apogeu.", StringComparison.Ordinal)
                        && !assembly.StartsWith("Apogeu.Operators.", StringComparison.Ordinal))
                    .ToList();
                foreach (var descriptor in otherModules)
                {
                    services.Remove(descriptor);
                }
            });
        });

        try
        {
            // Starts the host now: the migrations and the Development seed run here.
            _ = factory.Server;
        }
        catch
        {
            await factory.DisposeAsync().ConfigureAwait(false);
            throw;
        }

        return new ApogeuApiHost(factory, key);
    }

    /// <summary>The in-memory network to the Apogeu: the primary handler of the DemoCasino's "Apogeu" client.</summary>
    public HttpMessageHandler CreateHandler() => _factory.Server.CreateHandler();

    /// <summary>
    /// <c>GET /api/v1/games</c> asked directly to the Apogeu as the demo operator, signed with the independent reference of
    /// SPEC-0009 (<see cref="ReferenceSignature"/>): what the catalog really answers, to compare with the lobby.
    /// </summary>
    public async Task<JsonElement> ListGamesAsync(CancellationToken cancellationToken)
    {
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = DemoCasinoHost.ApogeuBaseUrl });
        using var request = new HttpRequestMessage(HttpMethod.Get, new Uri(GamesPath, UriKind.Relative));
        var timestamp = DateTimeOffset.UtcNow.ToUnixTimeSeconds();
        request.Headers.Add("X-Apogeu-Key", Key.Id);
        request.Headers.Add("X-Apogeu-Timestamp", timestamp.ToString(CultureInfo.InvariantCulture));
        request.Headers.Add("X-Apogeu-Signature", ReferenceSignature.Compute(Key.SecretBytes, timestamp, "GET", GamesPath, []));
        using var response = await client.SendAsync(request, cancellationToken).ConfigureAwait(false);
        var text = await response.Content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false);
        Assert.True(response.IsSuccessStatusCode, $"The Apogeu catalog answered {(int)response.StatusCode}: {text}");
        using var json = JsonDocument.Parse(text);
        return json.RootElement.Clone();
    }

    /// <summary>
    /// Opens a launch URL as the game does (SPEC-0045 IT-01, IT-02): <c>POST /api/v1/sessions { launchToken }</c> with the
    /// <c>lt</c> of <paramref name="launchUrl"/> (SPEC-0009@1: <c>launchUrl = {gameBaseUrl}/?lt={launchToken}</c>).
    /// </summary>
    public async Task<HttpResponseMessage> OpenLaunchAsync(Uri launchUrl, CancellationToken cancellationToken)
    {
        var body = JsonSerializer.Serialize(new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["launchToken"] = LaunchUrls.TokenOf(launchUrl),
        });
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = DemoCasinoHost.ApogeuBaseUrl });
        using var content = new StringContent(body, System.Text.Encoding.UTF8, "application/json");
        return await client.PostAsync(new Uri(SessionsPath, UriKind.Relative), content, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>The OpenAPI document the Apogeu Host generates (SPEC-0006), as it serves it: <c>GET /openapi/v1.json</c>.</summary>
    public async Task<JsonElement> OpenApiAsync(CancellationToken cancellationToken)
    {
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = DemoCasinoHost.ApogeuBaseUrl });
        using var response = await client.GetAsync(new Uri(OpenApiPath, UriKind.Relative), cancellationToken).ConfigureAwait(false);
        var text = await response.Content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false);
        Assert.True(response.IsSuccessStatusCode, $"GET {OpenApiPath} answered {(int)response.StatusCode}: {text}");
        using var json = JsonDocument.Parse(text);
        return json.RootElement.Clone();
    }

    /// <summary>Runs <paramref name="action"/> with the Apogeu's <see cref="ICatalogStore"/> (the admin side of the catalog).</summary>
    public async Task WithCatalogStoreAsync(Func<ICatalogStore, Task> action)
    {
        ArgumentNullException.ThrowIfNull(action);
        var scope = _factory.Services.CreateAsyncScope();
        await using (scope.ConfigureAwait(false))
        {
            await action(scope.ServiceProvider.GetRequiredService<ICatalogStore>()).ConfigureAwait(false);
        }
    }

    public ValueTask DisposeAsync() => _factory.DisposeAsync();
}
