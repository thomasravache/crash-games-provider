using System.Security.Cryptography;
using System.Text.RegularExpressions;
using Apogeu.AppHost.Tests.Support;
using Xunit;

namespace Apogeu.AppHost.Tests.Integration;

public sealed partial class SecretsScanTests
{
    private const string GitleaksImage = "zricethezav/gitleaks:v8.24.3";
    private const string AppHostDirectory = "src/backend/AppHost";
    private static readonly TimeSpan DockerTimeout = TimeSpan.FromMinutes(5);

    [Fact(DisplayName = "Dado o código do AppHost, quando o gitleaks e uma busca por literais de senha rodam, então nada é encontrado")]
    [Trait("Spec", "SPEC-0005:IT-05")]
    public async Task GivenAppHostSourceWhenGitleaksAndPasswordLiteralSearchRunThenNothingIsFound()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        var sources = await AppHostSourcesAsync(cancellationToken);

        // Control: the scan only proves something once the AppHost declares the credential-bearing resources.
        var program = sources.SingleOrDefault(path => string.Equals(Path.GetFileName(path), "Program.cs", StringComparison.Ordinal));
        Assert.True(program is not null, $"{AppHostDirectory}/Program.cs not found.");
        var programText = await File.ReadAllTextAsync(RepositoryRoot.Combine(program), cancellationToken);
        Assert.True(
            programText.Contains("AddPostgres(", StringComparison.Ordinal) && programText.Contains("AddKeycloak(", StringComparison.Ordinal),
            "The AppHost does not declare the postgres and keycloak resources yet, so a secrets scan over it proves nothing.");

        var scanRoot = CopyToScratch(sources);
        try
        {
            // Control: gitleaks runs and does detect a secret planted (at run time) in a scratch copy.
            var plantedRoot = Directory.CreateTempSubdirectory("apogeu-it05-planted-").FullName;
            try
            {
                await File.WriteAllTextAsync(
                    Path.Combine(plantedRoot, "planted.cs"),
                    $"var token = \"ghp_{RandomAlphanumeric(36)}\";\n",
                    cancellationToken);
                var planted = await GitleaksAsync(plantedRoot, cancellationToken);
                Assert.True(planted.ExitCode == 1, "Setup failed: gitleaks did not flag a planted token. " + planted.Describe());
            }
            finally
            {
                Directory.Delete(plantedRoot, recursive: true);
            }

            var scan = await GitleaksAsync(scanRoot, cancellationToken);
            Assert.True(scan.ExitCode is 0 or 1, "Setup failed: gitleaks did not run. " + scan.Describe());
            Assert.True(scan.ExitCode == 0, "gitleaks found secrets in the AppHost. " + scan.Describe());
        }
        finally
        {
            Directory.Delete(scanRoot, recursive: true);
        }

        AssertPasswordSearchRecognizesLiterals();
        var findings = await FindPasswordLiteralsAsync(sources, cancellationToken);
        Assert.True(findings.Count == 0, "Literal passwords/keys in the AppHost:" + Environment.NewLine + string.Join(Environment.NewLine, findings));
    }

    /// <summary>Control: the literal-password search recognizes the shapes it looks for, and only those.</summary>
    private static void AssertPasswordSearchRecognizesLiterals()
    {
        Assert.Matches(PasswordLiteral(), """builder.AddParameter("pg-password", "hunter2", secret: true);""");
        Assert.Matches(PasswordLiteral(), """{ "Parameters": { "postgres-password": "hunter2" } }""");
        Assert.Matches(PasswordLiteral(), "Host=db;Username=app;Password=hunter2");
        Assert.Matches(PasswordLiteral(), """var connection = "Password=hunter2;Host=db";""");
        Assert.DoesNotMatch(PasswordLiteral(), """builder.AddParameter("pg-password", secret: true);""");
        Assert.DoesNotMatch(PasswordLiteral(), """builder.AddPostgres("postgres", password: postgresPassword);""");
    }

    private static async Task<List<string>> FindPasswordLiteralsAsync(
        IReadOnlyList<string> sources,
        CancellationToken cancellationToken)
    {
        var findings = new List<string>();

        // packages.lock.json is generated by NuGet and only lists package ids and versions (e.g. "...UserSecrets").
        foreach (var source in sources.Where(path => !string.Equals(Path.GetFileName(path), "packages.lock.json", StringComparison.Ordinal)))
        {
            var lines = await File.ReadAllLinesAsync(RepositoryRoot.Combine(source), cancellationToken).ConfigureAwait(false);
            for (var index = 0; index < lines.Length; index++)
            {
                if (PasswordLiteral().IsMatch(lines[index]))
                {
                    findings.Add($"{source}:{index + 1}: {lines[index].Trim()}");
                }
            }
        }

        return findings;
    }

    /// <summary>
    /// A literal value assigned to a credential-like key (password, pwd, secret, key, token) in code, JSON or a
    /// connection string, or a literal value passed to <c>AddParameter(name, value, ...)</c>.
    /// </summary>
    [GeneratedRegex(
        """
        (?ix)
        (?:password|passwd|pwd|secret|api[-_]?key|token)[\w-]*"?\s*[:=]\s*(?:"[^"\s]+"|'[^'\s]+')
        | (?:^|[;"'])\s*(?:password|pwd)\s*=\s*[^;"'\s]+
        | AddParameter\s*\(\s*"[^"]+"\s*,\s*"[^"]*"
        """,
        RegexOptions.CultureInvariant,
        matchTimeoutMilliseconds: 5000)]
    private static partial Regex PasswordLiteral();

    /// <summary>Files under the AppHost tracked by git or not ignored (build output excluded).</summary>
    private static async Task<IReadOnlyList<string>> AppHostSourcesAsync(CancellationToken cancellationToken)
    {
        var listing = await ProcessRunner.RunAsync(
            "git",
            ["ls-files", "--cached", "--others", "--exclude-standard", "--", AppHostDirectory],
            RepositoryRoot.Path,
            TimeSpan.FromMinutes(1),
            cancellationToken).ConfigureAwait(false);
        Assert.True(listing.ExitCode == 0, "Setup failed: git ls-files. " + listing.Describe());

        var files = listing.Output
            .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Where(path => File.Exists(RepositoryRoot.Combine(path)))
            .ToList();
        Assert.True(files.Count > 0, $"Setup failed: no files found under {AppHostDirectory}.");
        return files;
    }

    private static string CopyToScratch(IReadOnlyList<string> sources)
    {
        var root = Directory.CreateTempSubdirectory("apogeu-it05-apphost-").FullName;
        foreach (var source in sources)
        {
            var target = Path.Combine(root, source);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.Copy(RepositoryRoot.Combine(source), target);
        }

        return root;
    }

    /// <summary>Runs gitleaks (container) in directory mode; exit code 0 = nothing found, 1 = leaks found.</summary>
    private static Task<ProcessResult> GitleaksAsync(string directory, CancellationToken cancellationToken) =>
        ProcessRunner.RunAsync(
            "docker",
            ["run", "--rm", "-v", $"{directory}:/scan:ro", GitleaksImage, "dir", "/scan", "--no-banner", "--redact", "--verbose", "--exit-code", "1"],
            RepositoryRoot.Path,
            DockerTimeout,
            cancellationToken);

    private static string RandomAlphanumeric(int length)
    {
        const string alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
        return RandomNumberGenerator.GetString(alphabet, length);
    }
}
