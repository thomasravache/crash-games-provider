using System.Security.Cryptography;
using Microsoft.IdentityModel.JsonWebTokens;
using Microsoft.IdentityModel.Tokens;

namespace Apogeu.Betting.Tests.Support;

/// <summary>
/// Player sessions of SPEC-0009 §4 for the integration hosts: a JWT signed with HS256 by the key the host is configured with
/// (<c>Security:PlayerSession:SigningKey</c>), issuer <c>apogeu</c>, audience <c>apogeu-game</c>, valid for 8 h, with the
/// claims <c>sub</c>, <c>op</c>, <c>sala</c>, <c>cur</c> and <c>mode</c> — validated by the real player-session scheme.
/// </summary>
internal static class BettingSessions
{
    public const string SettingName = "Security:PlayerSession:SigningKey";

    public const string Operator = "demo";

    public const string Currency = "BRL";

    private static readonly JsonWebTokenHandler Handler = new() { SetDefaultTimesOnTokenCreation = false };

    /// <summary>A new signing key (base64 of 32 random bytes), generated by the test (ADR-0014: no real secret anywhere).</summary>
    public static string NewSigningKey() => Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));

    /// <summary>A session of <paramref name="player"/> in the room <c>demo</c>, BRL, in <paramref name="mode"/> (<c>demo</c> or <c>real</c>).</summary>
    public static string Issue(string signingKey, string player, string mode = "demo")
    {
        var now = DateTime.UtcNow;
        return Handler.CreateToken(new SecurityTokenDescriptor
        {
            Issuer = "apogeu",
            Audience = "apogeu-game",
            IssuedAt = now,
            NotBefore = now,
            Expires = now + TimeSpan.FromHours(8),
            Claims = new Dictionary<string, object>(StringComparer.Ordinal)
            {
                ["sub"] = player,
                ["op"] = Operator,
                ["sala"] = BettingSala.SalaId,
                ["cur"] = Currency,
                ["mode"] = mode,
                [JwtRegisteredClaimNames.Jti] = Guid.NewGuid().ToString("N"),
            },
            SigningCredentials = new SigningCredentials(new SymmetricSecurityKey(Convert.FromBase64String(signingKey)), SecurityAlgorithms.HmacSha256),
        });
    }
}
