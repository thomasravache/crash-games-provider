using System.Security.Cryptography;
using Apogeu.Operators.Infrastructure.Catalog;
using Apogeu.Security.Tests.Support;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.AspNetCore.TestHost;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Time.Testing;

namespace Apogeu.Operators.Tests.Support;

/// <summary>
/// The real Host in memory (WebApplicationFactory) in Development on real PostgreSQL and Redis, configured only with values
/// generated by the test (ADR-0014): one demo API key, the session signing key and the game base URL. The Operators hosted
/// services stay, so the migrations and the Development seed (demo operator, catalog and limits) run through the real path;
/// the other modules' hosted services are removed. The clock is a <see cref="FakeTimeProvider"/> at the current time.
/// </summary>
internal sealed class OperatorsApiHost : IAsyncDisposable
{
    public static readonly Uri BaseAddress = new("https://api.apogeu.test");

    private readonly WebApplicationFactory<Program> _factory;

    private OperatorsApiHost(WebApplicationFactory<Program> factory, FakeTimeProvider clock, TestApiKey key)
    {
        _factory = factory;
        Clock = clock;
        Key = key;
    }

    public FakeTimeProvider Clock { get; }

    /// <summary>The active API key of the demo operator.</summary>
    public TestApiKey Key { get; }

    public static async Task<OperatorsApiHost> StartAsync(string postgresServerConnectionString, string redisConnectionString, CancellationToken cancellationToken)
    {
        var database = await TestDatabase.CreateAsync(postgresServerConnectionString, cancellationToken).ConfigureAwait(false);
        var clock = new FakeTimeProvider(DateTimeOffset.FromUnixTimeMilliseconds(DateTimeOffset.UtcNow.ToUnixTimeMilliseconds()));
        var key = TestApiKey.Generate();
        var signingKey = Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));

        var factory = new WebApplicationFactory<Program>().WithWebHostBuilder(host =>
        {
            host.UseEnvironment("Development");
            host.UseSetting("ConnectionStrings:apogeu", database);
            host.UseSetting("ConnectionStrings:redis", redisConnectionString);
            host.UseSetting("Operators:GameBaseUrl", "https://game.apogeu.test");
            host.UseSetting("Operators:Demo:ApiKeys:0:Id", key.Id);
            host.UseSetting("Operators:Demo:ApiKeys:0:Secret", key.Secret);
            host.UseSetting("Security:PlayerSession:SigningKey", signingKey);
            host.ConfigureTestServices(services =>
            {
                services.Replace(ServiceDescriptor.Singleton<TimeProvider>(clock));
                var otherModules = services
                    .Where(d => d.ServiceType == typeof(IHostedService)
                        && d.ImplementationType?.Assembly.GetName().Name is { } assembly
                        && assembly.StartsWith("Apogeu.", StringComparison.Ordinal)
                        && !assembly.StartsWith("Apogeu.Operators.", StringComparison.Ordinal))
                    .ToList();
                foreach (var descriptor in otherModules)
                {
                    services.Remove(descriptor);
                }
            });
        });

        try
        {
            // Starts the host now: the migrations and the Development seed run here.
            _ = factory.Server;
        }
        catch
        {
            await factory.DisposeAsync().ConfigureAwait(false);
            throw;
        }

        return new OperatorsApiHost(factory, clock, key);
    }

    public HttpClient CreateClient() =>
        _factory.CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = BaseAddress, AllowAutoRedirect = false });

    public long UnixNow() => Clock.GetUtcNow().ToUnixTimeSeconds();

    /// <summary>Runs <paramref name="action"/> with the host's <see cref="ICatalogStore"/>, in a DI scope of its own.</summary>
    public async Task WithCatalogStoreAsync(Func<ICatalogStore, Task> action)
    {
        ArgumentNullException.ThrowIfNull(action);
        var scope = _factory.Services.CreateAsyncScope();
        await using (scope.ConfigureAwait(false))
        {
            await action(scope.ServiceProvider.GetRequiredService<ICatalogStore>()).ConfigureAwait(false);
        }
    }

    public ValueTask DisposeAsync() => _factory.DisposeAsync();
}
