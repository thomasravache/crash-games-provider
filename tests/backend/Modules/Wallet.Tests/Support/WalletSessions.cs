using System.Security.Cryptography;
using Microsoft.IdentityModel.JsonWebTokens;
using Microsoft.IdentityModel.Tokens;

namespace Apogeu.Wallet.Tests.Support;

/// <summary>
/// Player sessions of SPEC-0009 §4 for the wallet host: a JWT signed with HS256 by the provider key the host is configured
/// with (<c>Security:PlayerSession:SigningKey</c>), issuer <c>apogeu</c>, audience <c>apogeu-game</c>, valid for 8 h, with
/// the claims <c>sub</c>, <c>op</c>, <c>sala</c>, <c>cur</c> and <c>mode</c>, validated by the real player-session scheme of the Host.
/// </summary>
internal static class WalletSessions
{
    public const string SettingName = "Security:PlayerSession:SigningKey";

    private const string Issuer = "apogeu";
    private const string Audience = "apogeu-game";
    private static readonly TimeSpan Lifetime = TimeSpan.FromHours(8);
    private static readonly JsonWebTokenHandler Handler = new() { SetDefaultTimesOnTokenCreation = false };

    /// <summary>A new signing key (base64 of 32 random bytes), generated by the test (ADR-0014: no real secret anywhere).</summary>
    public static string NewSigningKey() => Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));

    /// <summary>A demo BRL session of <paramref name="playerId"/> at the demo operator, signed with <paramref name="signingKey"/>.</summary>
    public static string Issue(string signingKey, string playerId, string mode = "demo")
    {
        var now = DateTime.UtcNow;
        return Handler.CreateToken(new SecurityTokenDescriptor
        {
            Issuer = Issuer,
            Audience = Audience,
            IssuedAt = now,
            NotBefore = now,
            Expires = now + Lifetime,
            Claims = new Dictionary<string, object>(StringComparer.Ordinal)
            {
                ["sub"] = playerId,
                ["op"] = WalletExpectations.Demo.Value,
                ["sala"] = "demo",
                ["cur"] = WalletExpectations.Brl.Code,
                ["mode"] = mode,
                [JwtRegisteredClaimNames.Jti] = Guid.NewGuid().ToString("N"),
            },
            SigningCredentials = new SigningCredentials(new SymmetricSecurityKey(Convert.FromBase64String(signingKey)), SecurityAlgorithms.HmacSha256),
        });
    }
}
