using Apogeu.Repository.Tests.Support;

namespace Apogeu.Deploy.Tests.Support;

/// <summary>
/// The scripts of tools/deploy and the interface the tests fix for them (SPEC-0066 §6; documented in tests/deploy/README.md).
/// Every script reads its configuration from the environment; the defaults are the ones of the VPS.
/// </summary>
internal static class DeployScripts
{
    public const string Deploy = "tools/deploy/vps-deploy";
    public const string Rollback = "tools/deploy/vps-rollback";
    public const string Backup = "tools/deploy/backup";
    public const string Restore = "tools/deploy/restore";
    public const string Caddyfile = "infra/caddy/Caddyfile";

    /// <summary>Directory of the deployment (checkout, releases, .env, backups). Default on the VPS: chosen by the script.</summary>
    public const string DeployDirVariable = "APOGEU_DEPLOY_DIR";

    /// <summary>Git repository the deploy fetches the ref from (default: the GitHub repository).</summary>
    public const string RepositoryVariable = "APOGEU_DEPLOY_REPO";

    /// <summary>Docker compose project name (default <c>apogeu</c>).</summary>
    public const string ProjectVariable = "APOGEU_COMPOSE_PROJECT";

    /// <summary>Base domain of the three sites (default <c>143-95-218-240.sslip.io</c>); also read by the Caddyfile.</summary>
    public const string DomainVariable = "APOGEU_DOMAIN";

    /// <summary>Host ports of the proxy (default 80 and 443).</summary>
    public const string HttpPortVariable = "APOGEU_HTTP_PORT";

    public const string HttpsPortVariable = "APOGEU_HTTPS_PORT";

    /// <summary>Prefix of the image names of a version: <c>{prefix}-api</c>, <c>{prefix}-demo-casino</c>, <c>{prefix}-proxy</c>, tagged with the commit.</summary>
    public const string ImagePrefixVariable = "APOGEU_IMAGE_PREFIX";

    /// <summary>
    /// Build hook, relative to the root of the checkout and run there, in place of <c>aspire publish</c> and the image builds.
    /// Receives APOGEU_VERSION, API_IMAGE, DEMO_CASINO_IMAGE and PROXY_IMAGE; leaves infra/compose/out/docker-compose.yaml
    /// and the three images.
    /// </summary>
    public const string BuildHookVariable = "APOGEU_DEPLOY_BUILD";

    /// <summary>Smoke command (absolute path) in place of tools/deploy/smoke; exit ≠ 0 makes the deploy go back.</summary>
    public const string SmokeVariable = "APOGEU_DEPLOY_SMOKE";

    /// <summary>Seconds the deploy waits for the health of a version before going back (the tests keep it short).</summary>
    public const string HealthTimeoutVariable = "APOGEU_DEPLOY_HEALTH_TIMEOUT";

    /// <summary>Backup: container of the PostgreSQL (default: the postgres service of the compose project).</summary>
    public const string PostgresContainerVariable = "APOGEU_POSTGRES_CONTAINER";

    /// <summary>
    /// Backup and restore: Docker volume of the Data Protection keys (default: the dataprotection-keys volume of the compose
    /// project, <c>{project}_dataprotection-keys</c>). SPEC-0066 Emenda v3.
    /// </summary>
    public const string KeysVolumeVariable = "APOGEU_KEYS_VOLUME";

    /// <summary>Backup: directory of the dumps (default: backups/ under the deployment directory).</summary>
    public const string BackupDirVariable = "APOGEU_BACKUP_DIR";

    /// <summary>Secrets of the .env, random, generated by the deploy on the first run (SPEC-0065@2 §6).</summary>
    public static readonly string[] Secrets =
    [
        "OPERATORS_DEMO_KEY_ID",
        "OPERATORS_DEMO_KEY_SECRET",
        "PLAYER_SESSION_SIGNING_KEY",
        "POSTGRES_PASSWORD",
        "REDIS_PASSWORD",
    ];

    /// <summary>The other variables of the .env of the contract (SPEC-0065@2 §6) besides the images of the version.</summary>
    public static readonly string[] Settings = ["BACKOFFICE_AUTHORITY", "PUBLIC_API_URL", "PUBLIC_GAME_URL"];

    /// <summary>Image variables of the version (SPEC-0065@2 §6).</summary>
    public static readonly string[] Images = ["API_IMAGE", "DEMO_CASINO_IMAGE"];

    public static string PathOf(string script) => RepositoryRoot.Combine(script.Split('/'));

    /// <summary>Runs a script of the repository with the given environment, from the repository root.</summary>
    public static Task<ProcessResult> RunAsync(
        string script,
        IEnumerable<string> arguments,
        IReadOnlyDictionary<string, string> environment,
        CancellationToken cancellationToken) =>
        ProcessRunner.RunAsync(PathOf(script), arguments, RepositoryRoot.Path, ProcessRunner.LongTimeout, environment, cancellationToken);
}
