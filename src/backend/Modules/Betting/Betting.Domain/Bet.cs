using Apogeu.Betting.Contracts;
using Apogeu.Rounds.Contracts;

namespace Apogeu.Betting.Domain;

/// <summary>
/// A bet of a player in one panel (SPEC-0022 §6). A bet received before <c>BettingEndsAt</c> of the room's round (server
/// clock) is <see cref="BetStatus.Placed"/> in it; one received at or after it, or while no round is open, is
/// <see cref="BetStatus.Queued"/> for the next round.
/// </summary>
public sealed class Bet
{
    /// <summary>The smallest automatic cash-out accepted (SPEC-0022 §4).</summary>
    public const decimal MinAutoCashOut = 1.01m;

    /// <summary>The largest number of decimal places of an amount (SPEC-0022 §4).</summary>
    private const int AmountScale = 2;

    private Bet(Guid id, BetOwner owner, BetRequest request, BetStatus status, RoundId? roundId, long? roundNumber)
    {
        Id = id;
        ClientBetId = request.ClientBetId;
        Owner = owner;
        Panel = request.Panel;
        Amount = request.Amount;
        AutoCashOut = request.AutoCashOut;
        Status = status;
        RoundId = roundId;
        RoundNumber = roundNumber;
    }

    public Guid Id { get; }

    /// <summary>Idempotency key generated by the client.</summary>
    public Guid ClientBetId { get; }

    public BetOwner Owner { get; }

    /// <summary>Panel 1 or 2.</summary>
    public int Panel { get; }

    public decimal Amount { get; }

    public decimal? AutoCashOut { get; }

    public BetStatus Status { get; private set; }

    /// <summary>The round of the bet; <see langword="null"/> while it is queued for the next round.</summary>
    public RoundId? RoundId { get; private set; }

    /// <summary>The number of the round of the bet; <see langword="null"/> while it is queued.</summary>
    public long? RoundNumber { get; private set; }

    /// <summary>The multiplier of the cash-out; <see langword="null"/> unless <see cref="BetStatus.CashedOut"/> (SPEC-0023).</summary>
    public decimal? CashOutMultiplier { get; private set; }

    /// <summary>The payout of the cash-out; <see langword="null"/> unless <see cref="BetStatus.CashedOut"/> (SPEC-0023).</summary>
    public decimal? Payout { get; private set; }

    /// <summary>
    /// The payout of a cash-out (SPEC-0023 §6): <c>min(floor(amount × multiplier × 100)/100, maxWin)</c>, truncated in cents.
    /// </summary>
    public static decimal PayoutOf(decimal amount, decimal multiplier, decimal maxWin) =>
        Math.Min(Math.Floor(amount * multiplier * 100m) / 100m, maxWin);

    /// <summary>
    /// Validates a new bet of <paramref name="owner"/> against <paramref name="rules"/> and the player's non-final bets
    /// (<paramref name="openBets"/>), and places it in <paramref name="current"/> when its bets are open at
    /// <paramref name="now"/> (server clock), otherwise queues it for the next round. Codes: <c>INVALID_AMOUNT</c>,
    /// <c>BET_BELOW_MIN</c>, <c>BET_ABOVE_MAX</c>, <c>AUTO_CASHOUT_INVALID</c>, <c>INVALID_PANEL</c>, <c>PANEL_BUSY</c>.
    /// </summary>
    public static BetPlacement Place(
        Guid betId,
        BetOwner owner,
        BetRequest request,
        BetRules rules,
        RoundWindow? current,
        DateTimeOffset now,
        IReadOnlyCollection<Bet> openBets)
    {
        ArgumentNullException.ThrowIfNull(owner);
        ArgumentNullException.ThrowIfNull(request);
        ArgumentNullException.ThrowIfNull(rules);
        ArgumentNullException.ThrowIfNull(openBets);
        if (Validate(request, rules) is { } code)
        {
            return new BetPlacementRejected(code);
        }

        // The phase boundary is the server clock: a bet received at BettingEndsAt is already for the next round.
        var bet = current is { Phase: RoundPhase.Betting } open && now < open.BettingEndsAt
            ? new Bet(betId, owner, request, BetStatus.Placed, open.RoundId, open.RoundNumber)
            : new Bet(betId, owner, request, BetStatus.Queued, roundId: null, roundNumber: null);

        return openBets.Any(bet.SharesPanelWith)
            ? new BetPlacementRejected(BettingErrorCodes.PanelBusy)
            : new BetPlacementAccepted(bet);
    }

    /// <summary>
    /// Rebuilds a bet already accepted (persistence): no rule is checked again.
    /// </summary>
    public static Bet Restore(
        Guid id,
        BetOwner owner,
        BetRequest request,
        BetStatus status,
        RoundId? roundId,
        long? roundNumber)
    {
        ArgumentNullException.ThrowIfNull(owner);
        ArgumentNullException.ThrowIfNull(request);
        return new Bet(id, owner, request, status, roundId, roundNumber);
    }

    /// <summary>
    /// Rebuilds a bet already accepted (persistence), with its cash-out when it is <see cref="BetStatus.CashedOut"/>
    /// (<paramref name="cashOutMultiplier"/> and <paramref name="payout"/>, both <see langword="null"/> otherwise).
    /// </summary>
    public static Bet Restore(
        Guid id,
        BetOwner owner,
        BetRequest request,
        BetStatus status,
        RoundId? roundId,
        long? roundNumber,
        decimal? cashOutMultiplier,
        decimal? payout) =>
        new(id, owner ?? throw new ArgumentNullException(nameof(owner)), request ?? throw new ArgumentNullException(nameof(request)), status, roundId, roundNumber)
        {
            CashOutMultiplier = cashOutMultiplier,
            Payout = payout,
        };

    /// <summary>
    /// The room opened the bets of <paramref name="opened"/>: a queued bet becomes placed in it (the player gets
    /// <c>BetActivated</c>). Returns whether the bet changed.
    /// </summary>
    public bool Activate(RoundWindow opened)
    {
        ArgumentNullException.ThrowIfNull(opened);
        if (Status != BetStatus.Queued)
        {
            return false;
        }

        Status = BetStatus.Placed;
        RoundId = opened.RoundId;
        RoundNumber = opened.RoundNumber;
        return true;
    }

    /// <summary>The flight of <paramref name="roundId"/> started: a bet placed in it becomes active.</summary>
    public void StartFlight(RoundId roundId)
    {
        if (Status == BetStatus.Placed && RoundId == roundId)
        {
            Status = BetStatus.Active;
        }
    }

    /// <summary>
    /// Cashes out an active bet at <paramref name="multiplier"/> (decided by the leader, SPEC-0023): it becomes
    /// <see cref="BetStatus.CashedOut"/> with <see cref="PayoutOf"/> limited by <paramref name="maxWin"/>. A bet already cashed
    /// out answers its original <see cref="BetCashOutAccepted"/>; a placed, queued or cancelled one <c>BET_NOT_ACTIVE</c>.
    /// </summary>
    public BetCashOut CashOut(decimal multiplier, decimal maxWin)
    {
        switch (Status)
        {
            case BetStatus.CashedOut:
                // Idempotent: the cash-out the bet already has.
                return new BetCashOutAccepted(CashOutMultiplier!.Value, Payout!.Value);
            case not BetStatus.Active:
                return new BetCashOutRejected(BettingErrorCodes.BetNotActive);
        }

        Status = BetStatus.CashedOut;
        CashOutMultiplier = multiplier;
        Payout = PayoutOf(Amount, multiplier, maxWin);
        return new BetCashOutAccepted(multiplier, Payout.Value);
    }

    /// <summary>
    /// Cancels the bet with its full amount refunded while it is queued, or placed in a round whose flight has not started;
    /// otherwise <c>CANCEL_NOT_ALLOWED</c>.
    /// </summary>
    public BetCancellation Cancel(RoundWindow? current, DateTimeOffset now)
    {
        var allowed = Status switch
        {
            BetStatus.Queued => true,
            BetStatus.Placed => current is { Phase: RoundPhase.Betting } open && open.RoundId == RoundId && now < open.BettingEndsAt,
            _ => false,
        };
        if (!allowed)
        {
            return new BetCancellationRejected(BettingErrorCodes.CancelNotAllowed);
        }

        Status = BetStatus.Cancelled;
        return new BetCancellationAccepted(Amount);
    }

    private static string? Validate(BetRequest request, BetRules rules)
    {
        if (request.Panel is not (1 or 2))
        {
            return BettingErrorCodes.InvalidPanel;
        }

        if (request.Amount <= 0 || decimal.Round(request.Amount, AmountScale) != request.Amount)
        {
            return BettingErrorCodes.InvalidAmount;
        }

        if (request.Amount < rules.MinBet)
        {
            return BettingErrorCodes.BetBelowMin;
        }

        if (request.Amount > rules.MaxBet)
        {
            return BettingErrorCodes.BetAboveMax;
        }

        return request.AutoCashOut is { } autoCashOut && (autoCashOut < MinAutoCashOut || autoCashOut > rules.MaxAutoCashOut)
            ? BettingErrorCodes.AutoCashOutInvalid
            : null;
    }

    /// <summary>
    /// Whether the panel of this new bet is held by <paramref name="other"/>, a non-final bet of the same player in the same
    /// panel: a queued bet holds its panel until it is activated or cancelled (emenda 3), whatever round the new bet is for;
    /// a placed bet holds it for its round.
    /// </summary>
    private bool SharesPanelWith(Bet other) =>
        other.Owner == Owner
        && other.Panel == Panel
        && (other.Status == BetStatus.Queued || (other.Status != BetStatus.Cancelled && Status != BetStatus.Queued && other.RoundId == RoundId));
}
